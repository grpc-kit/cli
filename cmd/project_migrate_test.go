func TestProjectMigrateRejectsUnsupportedSource(t *testing.T) {
	previous := vars.ReleaseVersion
	vars.ReleaseVersion = "0.3.9-beta.1"
	t.Cleanup(func() { vars.ReleaseVersion = previous })

	root := writeCommandTestProject(t)
	environmentPath := filepath.Join(root, "scripts", "env")
	body, err := os.ReadFile(environmentPath)
	if err != nil {
		t.Fatal(err)
	}
	body = []byte(strings.ReplaceAll(string(body), "0.3.9-beta.1", "0.4.0"))
	if err := os.WriteFile(environmentPath, body, 0o600); err != nil {
		t.Fatal(err)
	}

	cmd := newRootCommand(func() error { return nil })
	cmd.SetOut(io.Discard)
	cmd.SetErr(io.Discard)
	cmd.SetArgs([]string{"project", "migrate", root})

	err = cmd.Execute()
	if err == nil || !strings.Contains(err.Error(), "migration plan is unsupported") {
		t.Fatalf("Execute() error = %v, want unsupported source", err)
	}
}

