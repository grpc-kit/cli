func TestProjectMigrateRejectsExtraArguments(t *testing.T) {
	cmd := newRootCommand(func() error { return nil })
	cmd.SetOut(io.Discard)
	cmd.SetErr(io.Discard)
	cmd.SetArgs([]string{"project", "migrate", "one", "two"})

	if err := cmd.Execute(); err == nil {
		t.Fatal("Execute() error = nil, want an argument validation error")
	}
}

func TestProjectMigratePreviewAllowsPrereleaseVersion(t *testing.T) {
	previous := vars.ReleaseVersion
	vars.ReleaseVersion = "0.3.9-beta.1"
	t.Cleanup(func() { vars.ReleaseVersion = previous })

	cmd := newRootCommand(func() error { return nil })
	var output bytes.Buffer
	cmd.SetOut(&output)
	cmd.SetErr(io.Discard)
	cmd.SetArgs([]string{"project", "migrate", writeCommandTestProject(t)})

	if err := cmd.Execute(); err != nil {
		t.Fatalf("Execute() error = %v", err)
	}
	if !strings.Contains(output.String(), "Status: ready") || !strings.Contains(output.String(), "Apply blocked [release_version]") {
		t.Fatalf("output = %q", output.String())
	}
}

