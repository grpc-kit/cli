func TestProjectMigrateApply(t *testing.T) {
	previous := vars.ReleaseVersion
	vars.ReleaseVersion = "0.4.0"
	t.Cleanup(func() { vars.ReleaseVersion = previous })

	root := writeCommandTestProject(t)
	for _, args := range [][]string{
		{"init"},
		{"add", "."},
		{"-c", "user.name=grpc-kit-test", "-c", "user.email=test@grpc-kit.invalid", "commit", "-m", "fixture"},
	} {
		command := exec.Command("git", append([]string{"-C", root}, args...)...)
		if output, err := command.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, output)
		}
	}

	cmd := newRootCommand(func() error { return nil })
	var output bytes.Buffer
	cmd.SetOut(&output)
	cmd.SetErr(io.Discard)
	cmd.SetArgs([]string{"project", "migrate", root, "--apply"})

	if err := cmd.Execute(); err != nil {
		t.Fatalf("Execute() error = %v\n%s", err, output.String())
	}
	if !strings.Contains(output.String(), "Managed files migrated: 1") {
		t.Fatalf("output = %q", output.String())
	}
	if !strings.Contains(output.String(), "Managed files migrated; project compatibility is not yet verified.") {
		t.Fatalf("output does not explain compatibility status: %q", output.String())
	}
	environment, err := os.ReadFile(filepath.Join(root, "scripts", "env"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(environment), "CLI_VERSION=0.4.0") {
		t.Fatalf("scripts/env was not migrated:\n%s", environment)
	}
}

func writeCommandTestProject(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "scripts"), 0o755); err != nil {
		t.Fatal(err)
	}
	environment := `# Code generated by "grpc-kit-cli/0.3.9-beta.1". DO NOT EDIT.
CLI_VERSION=0.3.9-beta.1
PRODUCT_CODE=oneops
SHORT_NAME=spider
API_VERSION=v1
APPNAME=${PRODUCT_CODE}-${SHORT_NAME}-${API_VERSION}
SERVICE_CODE=${SHORT_NAME}.${API_VERSION}.${PRODUCT_CODE}
`
	if err := os.WriteFile(filepath.Join(root, "scripts", "env"), []byte(environment), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module git.lmq.io/kaopuvm/spider\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	return root
}
