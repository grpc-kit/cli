func TestIsKnownLegacyMarkerFile(t *testing.T) {
	if !IsKnownLegacyMarkerFile(legacyPublicEmbedPath, []byte(legacyPublicEmbedFixture)) {
		t.Fatal("exact frozen fixture was not recognized")
	}
	if IsKnownLegacyMarkerFile("other/embed.go", []byte(legacyPublicEmbedFixture)) {
		t.Fatal("fixture was recognized at another path")
	}
	if IsKnownLegacyMarkerFile(legacyPublicEmbedPath, []byte(legacyPublicEmbedFixture+"\n")) {
		t.Fatal("modified fixture was recognized")
	}
}
