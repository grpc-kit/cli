func TestSpiderSourceFixture(t *testing.T) {
	fixture := SpiderSourceFixture()
	if fixture.Commit != spiderFixtureCommit || fixture.ProjectCLIVersion != "0.3.9-beta.1" || len(fixture.Files) != 6 {
		t.Fatalf("SpiderSourceFixture() = %#v", fixture)
	}
	fixture.Files[legacyPublicEmbedPath] = "changed"
	if SpiderSourceFixture().Files[legacyPublicEmbedPath] != legacyPublicEmbedSHA256 {
		t.Fatal("SpiderSourceFixture returned mutable package state")
	}
}

